SEED_DIR_NAME = ".aipass"
SEED_FILE_NAME = "passport.seed.json"
SEED_RELATIVE_PATH = f"{SEED_DIR_NAME}/{SEED_FILE_NAME}"

# The optional canonical field a seed-minted passport carries. schema_version
# stays 2.0.0 — this is an additive optional machine-local field, not a bump.
STAMP_KEY = "seed"
STAMP_FIELDS = ("version", "sha256")

# Facts that are true of ONE MACHINE and must never ship in a tracked seed.
# This tuple is the privacy leak-guard's definition as well as the strip list.
MACHINE_LOCAL_CITIZENSHIP = ("registered", "registry_id", "citizen_id", STAMP_KEY)

# Keys the 2.0 shape allows but does not require. class_extension exists on
# devpulse alone (DPLAN-0288 prose); the stamp exists only on a seed mint.
OPTIONAL_KEYS = {
    "citizenship": (STAMP_KEY,),
    "identity": ("class_extension",),
}

# Seeds are only defined for CORE citizens — the seed path in the ruling is
# ``src/aipass/<branch>/.aipass/passport.seed.json``. Residents live in
# ``projects/<project>/`` and belong to their own project's repo.
SEED_RESIDENCY = "core"

# Shape rules, kept deliberately small: enough that "invalid seed refuses" has
# teeth, not a second schema engine. Everything not listed must be a string —
# which is why ``traits`` is here: the 1.x fleet carried it as prose, and a
# string sneaking back in is the exact regression this table catches.
_FIELD_TYPES = {
    ("document_metadata", "tags"): (list, "a list"),
    ("identity", "what_i_do"): (list, "a list"),
    ("identity", "what_i_dont_do"): (list, "a list"),
    ("identity", "traits"): (list, "a list"),
    ("identity", "principles"): (list, "a list"),
    ("citizenship", "registered"): (bool, "true/false"),
    ("citizenship", "communications"): (bool, "true/false"),
    ("citizenship", "memory"): (bool, "true/false"),
}
_DEFAULT_FIELD_TYPE = (str, "a string")

# The stamp is the one field with a shape of its own — see _validate_stamp.
_STAMP_FIELD = {("citizenship", STAMP_KEY)}
_REQUIRED_NON_EMPTY = {
    ("document_metadata", "document_name"),
    ("document_metadata", "schema_version"),
    ("branch_info", "branch_name"),
    ("branch_info", "path"),
    ("citizenship", "residency"),
    ("identity", "citizen_class"),
}


class SeedError(Exception):
    """A seed that cannot be trusted. Callers refuse rather than write."""


def _key_order(section: str) -> tuple:
    """Canonical key order for a block, with the stamp appended to citizenship.

    The stamp's position is not a free choice: appending it is exactly what
    ``passport_migration._order_block`` does with a key it does not recognise,
    so a stamped passport is already in the order that module would emit.
    """
    if section == "citizenship":
        return KEY_ORDER["citizenship"] + (STAMP_KEY,)
    return KEY_ORDER[section]


