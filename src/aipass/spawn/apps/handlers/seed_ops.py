"""Passport seeds: the identity that ships with the repo (TDPLAN-0017).

A live passport is ``.trinity/passport.json`` and it is GITIGNORED, on purpose:
tracking it is pull-hostile (refusals, conflicts, ``reset --hard`` destroying an
agent's identity). The cost of that correctness is that five months of evolved
identity never reaches a clone — a fresh install mints every citizen from the one
generic template and the souls stay on the machine that grew them.

The seed closes that gap without touching the ignore. Each branch carries a
TRACKED ``.aipass/passport.seed.json`` — its live passport minus the facts that
are true only of one machine::

    citizenship.registered     the live file asserts it; a seed is not a citizen
    citizenship.registry_id    this machine's project credential
    citizenship.citizen_id     this machine's per-citizen UUID
    citizenship.seed           the stamp itself (see below)

Everything else is carried VERBATIM — residency, dates, path, the whole identity
block. The seed is not an example file and never a hand-edited one: it is
GENERATED by ``drone @spawn export-seeds`` from the live passport, which is what
keeps it from rotting the way a checked-in ``.env.example`` does.

The stamp is the one field that goes the other way. A passport minted FROM a seed
records which seed it came from::

    "citizenship": {..., "seed": {"version": "2.0.0", "sha256": "<file bytes>"}}

That is dpkg's md5sums pattern, and it is the whole reason update/merge machinery
could be deferred: with the stamp, a future "the shipped seed changed" question is
a three-way decision (shipped-then, shipped-now, live-now) instead of a guess.
A template mint gets NO stamp — it came from no seed, and an empty stamp would be
a claim about provenance that is not true.

**Schema knowledge is borrowed, never re-declared.** ``BLOCK_ORDER``, ``KEY_ORDER``
and ``SCHEMA_VERSION`` come from ``passport_migration`` — the module that already
owns the 2.0 shape. This module adds exactly one key to that knowledge
(``citizenship.seed``, optional) and appends it at the END of the citizenship
block, which is precisely where ``passport_migration._order_block`` puts a key it
does not recognise. A stamped passport therefore reorders to itself if the
migration is ever re-run over it.

**Refusal is the safe direction, in both lanes.** ``export_seeds`` refuses to
write a seed for a passport that does not validate (a bad seed shipped to every
clone is worse than a missing one), and ``mint_from_seed`` refuses to return a
passport that does not validate, so an invalid seed can never reach disk as
somebody's identity.
"""

